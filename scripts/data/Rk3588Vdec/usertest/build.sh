#!/bin/bash
# Build the VideoToolbox test program (vt_test.c) of the rkvdec2 decoder: an arm64-apple-ios17.0 executable, ad hoc signed by lld
# (CodeDirectory page size 4 KiB, what the 4K kernel wants), with the H.264 streams of ../streams and the CRC-32 of each of their pictures built in.
#
#   usertest/out/vt-test            the signed program
#   usertest/out/vt_streams.inc     what it includes (generated)
#
# build-rk3588-vdec.py carries the program in the kernel when it finds it (VdecTestFile.inc, vdec_test_file()); with boot-arg evb10-exec=1 the
# kernel writes it to /private/var/evb10 and starts it as init. A cdhash trusts ONE build of ONE binary: the owner trust bundle of the board has
# to list the one printed here (UniXNU-evb10's scripts or uefi-evb10/tools/xnu-probe/make-owner-trust-bundle.py, which takes the Mach-O files), its
# SHA-256 goes into the device's board.toml ([payload] trust_cache_sha256, second entry), and the kernel has to be built again (the file is in it).
#
# Environment: LLVM_BIN (clang-20 and lld), IOS_SDK (an iPhoneOS SDK with VideoToolbox, CoreMedia and CoreVideo stubs: 16.5 works).
#   CDHASH_PY   the MaliMetal usertest/cdhash.py (printing only; optional)
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
STREAMS="$HERE/../streams"
OUT="$HERE/out"
A="${LLVM_BIN:?set LLVM_BIN to the directory of clang-20}"
SDK="${IOS_SDK:?set IOS_SDK to an iPhoneOS SDK}"
mkdir -p "$OUT"
unset CCC_OVERRIDE_OPTIONS LLVM_CONFIG CLANG_BIN CC CXX

/usr/bin/python3 - "$STREAMS" "$OUT/vt_streams.inc" <<'EOF'
import pathlib, sys
streams, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
entries = []
with open(out, 'w') as f:
    f.write('// Generated by usertest/build.sh. Do not edit.\n')
    f.write('struct VtStream { const char *name; const unsigned char *data; unsigned size; const unsigned *crcs; unsigned crcCount; };\n')
    for i, path in enumerate(sorted(streams.glob('*.h264'))):
        data = path.read_bytes()
        crcs = [int(line, 16) for line in path.with_suffix('.crc').read_text().splitlines() if line.strip() and not line.startswith('#')]
        f.write('static const unsigned char kVtStream%d[] = {\n' % i)
        for k in range(0, len(data), 32):
            f.write(','.join(str(b) for b in data[k:k + 32]) + ',\n')
        f.write('};\nstatic const unsigned kVtCrcs%d[] = {%s};\n' % (i, ', '.join('0x%08x' % c for c in crcs)))
        entries.append('  {"%s", kVtStream%d, %d, kVtCrcs%d, %d},\n' % (path.stem, i, len(data), i, len(crcs)))
    f.write('static const struct VtStream kVtStreams[] = {\n' + ''.join(entries) + '};\n')
    f.write('static const unsigned kVtStreamCount = %d;\n' % len(entries))
print('%d streams' % len(entries))
EOF

"$A/clang-20" -target arm64-apple-ios17.0 -isysroot "$SDK" -O2 -Wall -Werror -I"$OUT" -fuse-ld=lld -B"$A" -Wl,-adhoc_codesign \
	"$HERE/vt_test.c" -framework CoreFoundation -framework CoreMedia -framework CoreVideo -framework VideoToolbox -framework IOKit \
	-o "$OUT/vt-test" 2> >(grep -v "directory not found" >&2) || { echo "error: compile failed" >&2; exit 1; }
ls -l "$OUT/vt-test"
if [ -n "${CDHASH_PY:-}" ]; then /usr/bin/python3 "$CDHASH_PY" "$OUT/vt-test"; fi
