// How deep the decoder core goes into the kernel stack (16 KiB per thread on arm64): the driver thread notes its own stack position, and the places the core
// calls back into the driver (allocations, jobs, pictures) record how far below it they are. A lower bound of the use, not the exact figure.
static uintptr_t gStackTop;
static uintptr_t gStackDeepest;
static inline void noteStack() {
  const uintptr_t here = reinterpret_cast<uintptr_t>(__builtin_frame_address(0));
  if (gStackTop && gStackTop > here && gStackTop - here > gStackDeepest) gStackDeepest = gStackTop - here;
}

// What the decoder core (MPP's parser and register generator, core/) asks of the program it is linked into.
extern "C" {
void *vdc_calloc(size_t size) {
  noteStack();
  return IOMallocZero(size);
}
void vdc_free(void *p, size_t size) {
  if (p) IOFree(p, size);
}
void vdc_log(int level, const char *line) { printf("rk3588-vdec: [mpp %d] %s\n", level, line); }
}

