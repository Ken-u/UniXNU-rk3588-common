"""Cut out of MPP's tree the one piece that cannot be compiled whole.

mpp/base/mpp_sys_cfg.c mixes two things: the picture buffer size and stride rules of the decoder (mpp_sys_dec_buf_chk_proc, plain arithmetic that
decides how big a decoded picture is and where its rows start: the register generator and the buffer slots both depend on it) and the kmpp object
machinery that makes the configuration reachable by name. Only the first is needed. This script copies the arithmetic, unchanged and in order, from
`typedef enum SysCfgAlignType_e` up to (not including) `mpp_sys_cfg_ioctl`, behind a header of includes, into OUT/mpp_sys_cfg_proc.c. It refuses to run
when the markers are not exactly where the pinned MPP has them.

    derive-mpp.py MPP_DIR OUT_DIR
"""
import os
import sys

FIRST = 'typedef enum SysCfgAlignType_e {'
LAST = 'MPP_RET mpp_sys_cfg_ioctl(MppSysCfg cfg)'

HEADER = '''// Generated by core/derive-mpp.py from mpp/base/mpp_sys_cfg.c of the pinned MPP: do not edit.
#define MODULE_TAG "mpp_sys_cfg"

#include <string.h>

#include "rk_mpp_cfg.h"

#include "mpp_env.h"
#include "mpp_mem.h"
#include "mpp_debug.h"
#include "mpp_common.h"
#include "mpp_soc.h"
#include "mpp_sys_cfg.h"
#include "mpp_compat_impl.h"

#define SYS_CFG_DBG_FUNC                (0x00000001)
#define SYS_CFG_DBG_INFO                (0x00000002)
#define SYS_CFG_DBG_SET                 (0x00000004)
#define SYS_CFG_DBG_GET                 (0x00000008)
#define SYS_CFG_DBG_DEC_BUF             (0x00000010)

static RK_U32 mpp_sys_cfg_debug = 0;

#define sys_cfg_dbg(flag, fmt, ...)     mpp_dbg_f(mpp_sys_cfg_debug, flag, fmt, ## __VA_ARGS__)
#define sys_cfg_dbg_dec_buf(fmt, ...)   sys_cfg_dbg(SYS_CFG_DBG_DEC_BUF, fmt, ## __VA_ARGS__)

'''


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    mpp, out = sys.argv[1:]
    src = open(os.path.join(mpp, 'mpp/base/mpp_sys_cfg.c')).read()
    if src.count(FIRST) != 1 or src.count(LAST) != 1:
        sys.exit('mpp_sys_cfg.c is not the one this script was written for (markers missing or repeated)')
    a, b = src.index(FIRST), src.index(LAST)
    if a >= b:
        sys.exit('markers out of order')
    body = src[a:b]
    if 'mpp_sys_dec_buf_chk_proc' not in body or 'kmpp_' in body:
        sys.exit('the cut part is not what it should be')
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, 'mpp_sys_cfg_proc.c'), 'w') as f:
        f.write(HEADER + body)


main()
